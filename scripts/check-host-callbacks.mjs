// The native header declares the callback ABI. clang expands it; this command checks or writes its cgo registration.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const PREFIX = "sp_host_callback_";
const DIAGNOSTIC_PREFIX = "sp_host_diagnostic_callback_";

export function createHostCallbacks(header) {
  const ast = JSON.parse(execFileSync("clang", ["-x", "c-header", "-fsyntax-only", "-Xclang", "-ast-dump=json", header], {
    encoding: "utf8", maxBuffer: 1 << 26, stdio: ["ignore", "pipe", "pipe"],
  }));
  const names = new Set();
  const diagnostics = new Set();
  const entries = new Map();
  function visit(node) {
    if (node.kind === "FunctionDecl" && node.name?.startsWith(PREFIX)) { names.add(node.name.slice(PREFIX.length)); entries.set(node.name, node); }
    if (node.kind === "FunctionDecl" && node.name?.startsWith(DIAGNOSTIC_PREFIX)) { diagnostics.add(node.name.slice(DIAGNOSTIC_PREFIX.length)); entries.set(node.name, node); }
    for (const child of node.inner ?? []) visit(child);
  }
  visit(ast);
  if (names.size === 0) throw new Error(`${header}: no native callback entry points`);
  const base = callbackEntries(header, names, entries, false);
  const diagnostic = callbackEntries(header, diagnostics, entries, true);
  return {
    base: renderCallbacks(header, base, false), diagnostics: diagnostics.size ? renderCallbacks(header, diagnostic, true) : undefined,
    puregoBase: renderPuregoCallbacks(base, false),
    puregoDiagnostics: diagnostics.size ? renderPuregoCallbacks(diagnostic, true) : undefined,
    abiBase: renderTypes(header, base, false),
    abiDiagnostics: diagnostics.size ? renderTypes(header, diagnostic, true) : undefined,
    handlersBase: renderHandlers(base, false),
    handlersDiagnostics: diagnostics.size ? renderHandlers(diagnostic, true) : undefined,
  };
}

const ABI_IMPORT = "github.com/soksak-app/core/packages/host/go/src/platform/darwin/abi";
const GENERATED = "// Code generated by scripts/check-host-callbacks.mjs --write; DO NOT EDIT.";
function prologue(diagnostics, pkg) {
  return `${GENERATED}\n//go:build darwin${diagnostics ? " && diagnostics" : ""}\n\npackage ${pkg}\n`;
}
function formatted(source) { return execFileSync("gofmt", { input: source, encoding: "utf8" }); }

function renderHandlers(callbacks, diagnostics) {
  const factory = diagnostics ? "diagnosticCallbackHandlers" : "callbackHandlers";
  const profile = diagnostics ? "DiagnosticCallbacks" : "Callbacks";
  return formatted(`${prologue(diagnostics, "darwin")}
import "${ABI_IMPORT}"

func ${factory}() abi.${profile} {
\treturn abi.${profile}{
${callbacks.map((entry) => `\t\t${entry.field}: goHost_${entry.name},`).join("\n")}
\t}
}
`);
}

function callbackEntries(header, names, entries, diagnostics) {
  const prefix = diagnostics ? DIAGNOSTIC_PREFIX : PREFIX;
  return [...names].map((name) => {
    const node = entries.get(prefix + name);
    if (node.variadic) throw new Error(`${header}: unsupported variadic callback ${name}`);
    const resultC = node.type.qualType.split(" (")[0];
    const result = goType(header, resultC);
    if (result === "float64") throw new Error(`${header}: unsupported callback result double for ${name}`);
    const parametersC = (node.inner ?? []).filter((entry) => entry.kind === "ParmVarDecl").map((entry) => entry.type.qualType);
    const parameters = parametersC.map((type) => goType(header, type));
    return { name, field: name.split("_").map((part) => part[0].toUpperCase() + part.slice(1)).join(""), result, resultC, parameters, parametersC,
      signature: `func(${parameters.join(", ")})${result ? " " + result : ""}` };
  });
}

function renderTypes(header, callbacks, diagnostics) {
  const profile = diagnostics ? "DiagnosticCallbacks" : "Callbacks";
  const table = diagnostics ? "DiagnosticTable" : "CallbackTable";
  return formatted(`${prologue(diagnostics, "abi")}
${callbacks.some((entry) => entry.signature.includes("unsafe.Pointer")) ? 'import "unsafe"\n' : ""}
// ${profile} preserves the C signatures of ${basename(header)}.
// Native pointers are borrowed for the callback; integer contexts are never Go pointers.
type ${profile} struct {
${callbacks.map((entry) => `\t${entry.field} ${entry.signature}`).join("\n")}
}

// ${table} holds process-lifetime function addresses in the native header's field order.
type ${table} [${callbacks.length}]uintptr
`);
}

function nilChecks(callbacks, failure) {
  return callbacks.map((entry) => `\tif callbacks.${entry.field} == nil {
\t\treturn ${failure}fmt.Errorf("native callback is missing: ${entry.name}")
\t}`).join("\n");
}

function cgoType(header, type) {
  const value = type.replace(/\bconst\b/g, "").trim();
  if (/\*\s*$/.test(value)) {
    const pointed = value.replace(/\*\s*$/, "").trim();
    return pointed === "void" ? "unsafe.Pointer" : "*" + cgoType(header, pointed);
  }
  const names = { bool: "bool", _Bool: "bool", char: "char", int: "int", long: "long", "unsigned long": "ulong", "unsigned long long": "ulonglong", uint64_t: "uint64_t", uintptr_t: "uintptr_t", size_t: "size_t", double: "double", sp_input_held: "sp_input_held" };
  if (Object.hasOwn(names, value)) return "C." + names[value];
  throw new Error(`${header}: unsupported callback cgo type ${type}`);
}

function renderCallbacks(header, callbacks, diagnostics) {
  const profile = diagnostics ? "DiagnosticCallbacks" : "Callbacks";
  const table = diagnostics ? "sp_host_diagnostic_callbacks" : "sp_host_callbacks";
  const retained = diagnostics ? "diagnosticHandlers" : "callbackHandlers";
  const install = diagnostics ? "InstallDiagnosticCallbacks" : "InstallCallbacks";
  const wrappers = callbacks.map((entry) => {
    const parameters = entry.parametersC.map((type, index) => `arg${index} ${cgoType(header, type)}`).join(", ");
    const args = entry.parameters.map((type, index) => {
      if (type === "unsafe.Pointer" || type === "*unsafe.Pointer") return `arg${index}`;
      if (type.startsWith("*")) return `(${type.replace(/SpInputHeld/g, "abi.SpInputHeld")})(unsafe.Pointer(arg${index}))`;
      return `${type}(arg${index})`;
    }).join(", ");
    const result = entry.result ? cgoType(header, entry.resultC) : "";
    const call = `${retained}.${entry.field}(${args})`;
    return `//export goHost_${entry.name}
func goHost_${entry.name}(${parameters}) ${result} {
\t${result ? `return ${result}(${call})` : call}
}`;
  }).join("\n\n");
  return formatted(`${prologue(diagnostics, "bindings")}
/*
#cgo pkg-config: soksak-darwin
#include "${basename(header)}"
${callbacks.map((entry) => `extern ${entry.resultC} goHost_${entry.name}(${entry.parametersC.length ? entry.parametersC.map((type, index) => `${type} arg${index}`).join(", ") : "void"});`).join("\n")}
*/
import "C"

import (
\t"fmt"
\t"sync"
${callbacks.some((entry) => entry.parameters.some((type) => type.includes("*") || type.includes("unsafe.Pointer"))) ? '\t"unsafe"\n' : ""}
\t"${ABI_IMPORT}"
)

var ${retained} abi.${profile}
var ${retained}Mutex sync.Mutex
var ${retained}Installed bool

// ${install} installs once before native work. A failed native install leaves handlers unchanged.
func ${install}(callbacks abi.${profile}) error {
\t${retained}Mutex.Lock()
\tdefer ${retained}Mutex.Unlock()
\tif ${retained}Installed {
\t\treturn fmt.Errorf("native callback profile is already installed")
\t}
${nilChecks(callbacks, "")}
\tvar native C.${table}
${callbacks.map((entry) => `\tnative.${entry.name} = (*[0]byte)(C.goHost_${entry.name})`).join("\n")}
\tif failure := C.${table}_install(&native); failure != nil {
\t\treturn fmt.Errorf("native callback registration: %s", C.GoString(failure))
\t}
\t${retained} = callbacks
\t${retained}Installed = true
\treturn nil
}

${wrappers}
`);
}

// This ABI is Darwin LP64. Opaque native structs remain pointers owned by native code.
function goType(header, type) {
  const value = type.replace(/\bconst\b/g, "").trim();
  const primitives = { void: "", _Bool: "bool", bool: "bool", char: "byte", int: "int32", long: "int64", "unsigned long": "uint64", "unsigned long long": "uint64", uint64_t: "uint64", uintptr_t: "uintptr", size_t: "uint64", double: "float64" };
  if (Object.hasOwn(primitives, value)) return primitives[value];
  if (/\*\s*$/.test(value)) {
    const pointed = value.replace(/\*\s*$/, "").trim();
    if (pointed === "void") return "unsafe.Pointer";
    if (pointed === "sp_input_held") return "*SpInputHeld";
    const element = goType(header, pointed);
    if (element) return "*" + element;
  }
  throw new Error(`${header}: unsupported callback type ${type}`);
}

function renderPuregoCallbacks(callbacks, diagnostics) {
  const profile = diagnostics ? "DiagnosticCallbacks" : "Callbacks";
  const table = diagnostics ? "DiagnosticTable" : "CallbackTable";
  const bind = diagnostics ? "BindDiagnostic" : "Bind";
  const state = diagnostics ? "diagnosticAddresses" : "callbackAddresses";
  return formatted(`${prologue(diagnostics, "nativecallback")}
import (
\t"fmt"
\t"sync"
\t"github.com/ebitengine/purego"
\t"${ABI_IMPORT}"
)

var ${state}Mutex sync.Mutex
var ${state}Bound bool

// ${bind} creates process-lifetime addresses once. Reuse the returned table.
// Every callback is validated before any address is allocated. Native code copies the table.
func ${bind}(callbacks abi.${profile}) (abi.${table}, error) {
\t${state}Mutex.Lock()
\tdefer ${state}Mutex.Unlock()
\tif ${state}Bound {
\t\treturn abi.${table}{}, fmt.Errorf("native callback profile is already bound")
\t}
${nilChecks(callbacks, `abi.${table}{}, `)}
\ttable := abi.${table}{
${callbacks.map((entry) => `\t\tpurego.NewCallback(callbacks.${entry.field}),`).join("\n")}
\t}
\t${state}Bound = true
\treturn table, nil
}
`);
}

// An explicit primary output isolates fixture generation from every default target.
export function hostCallbackOutputPaths(values = {}) {
  const defaultOutput = (path) => values.output ? undefined : `${ROOT}${path}`;
  return {
    output: resolve(values.output ?? `${ROOT}packages/host/wailsv3/src/platform/darwin/bindings/callback_bindings.go`),
    puregoOutput: values["purego-output"] ?? defaultOutput("packages/host/mygo/src/platform/darwin/nativecallback/callback_bindings.go"),
    typesOutput: values["types-output"] ?? defaultOutput("packages/host/go/src/platform/darwin/abi/callback_types.go"),
    handlersOutput: values["handlers-output"] ?? defaultOutput("packages/host/go/src/platform/darwin/callback_handlers.go"),
    fixtureOutput: defaultOutput("packages/host/go/tests/platform/darwin/standalone/bindings/callback_bindings.go"),
    fixturePuregoOutput: defaultOutput("packages/host/go/tests/platform/darwin/standalone/nativecallback/callback_bindings.go"),
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { values } = parseArgs({ options: { header: { type: "string" }, output: { type: "string" }, "purego-output": { type: "string" }, "types-output": { type: "string" }, "handlers-output": { type: "string" }, write: { type: "boolean" } } });
    const header = resolve(values.header ?? `${ROOT}native/darwin/src/host_callbacks.h`);
    const { output, puregoOutput, typesOutput, handlersOutput, fixtureOutput, fixturePuregoOutput } = hostCallbackOutputPaths(values);
    const generated = createHostCallbacks(header);
    // The common Darwin package owns only plain Go types and handlers now.
    // Remove its former generated cgo registration through the same checked workflow.
    if (!values.output) {
      for (const path of [
        "packages/host/go/src/platform/darwin/callback_bindings.go",
        "packages/host/go/src/platform/darwin/callback_bindings_diagnostics.go",
        "packages/host/go/tests/platform/darwin/bindings/callback_bindings.go",
        "packages/host/go/tests/platform/darwin/bindings/callback_bindings_diagnostics.go",
      ]) {
        const legacy = `${ROOT}${path}`;
        if (!existsSync(legacy)) continue;
        if (!readFileSync(legacy, "utf8").startsWith(GENERATED)) throw new Error(`${legacy}: refusing to remove a file not owned by the callback generator`);
        if (!values.write) throw new Error(`${legacy}: obsolete cgo callback binding; run make create-host-callbacks`);
        unlinkSync(legacy);
      }
    }
    const files = [];
    for (const [baseFile, base, diagnostics] of [[output, generated.base, generated.diagnostics], ...(fixtureOutput ? [[resolve(fixtureOutput), generated.base, generated.diagnostics]] : []), ...(puregoOutput ? [[resolve(puregoOutput), generated.puregoBase, generated.puregoDiagnostics]] : []), ...(fixturePuregoOutput ? [[resolve(fixturePuregoOutput), generated.puregoBase, generated.puregoDiagnostics]] : []), ...(typesOutput ? [[resolve(typesOutput), generated.abiBase, generated.abiDiagnostics]] : []), ...(handlersOutput ? [[resolve(handlersOutput), generated.handlersBase, generated.handlersDiagnostics]] : [])]) {
      if (!baseFile.endsWith(".go")) throw new Error(`${baseFile}: callback binding output must end in .go`);
      files.push([baseFile, base]);
      const diagnosticFile = baseFile.slice(0, -3) + "_diagnostics.go";
      if (diagnostics) files.push([diagnosticFile, diagnostics]);
      else if (existsSync(diagnosticFile)) {
        const existing = readFileSync(diagnosticFile, "utf8");
        if (!existing.startsWith("// Code generated by scripts/check-host-callbacks.mjs --write; DO NOT EDIT.")) {
          throw new Error(`${diagnosticFile}: refusing to remove a file not owned by the callback generator`);
        }
        if (!values.write) throw new Error(`${diagnosticFile}: obsolete diagnostic callback binding; run make create-host-callbacks`);
        unlinkSync(diagnosticFile);
      }
    }
    for (const [file, text] of files) {
      const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
      if (current !== text) {
        if (!values.write) throw new Error(`${file}: callback binding is stale; run make create-host-callbacks`);
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, text);
      }
    }
    process.stdout.write(`Host callback binding ${values.write ? "written" : "checked"}: ${output}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}${error.stderr ? `\n${error.stderr}` : ""}\n`);
    process.exitCode = 1;
  }
}
