// The native header declares the callback ABI. clang expands it; this command checks or writes its cgo registration.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const PREFIX = "sp_host_callback_";
const DIAGNOSTIC_PREFIX = "sp_host_diagnostic_callback_";

export function createHostCallbacks(header) {
  const ast = JSON.parse(execFileSync("clang", ["-x", "c-header", "-fsyntax-only", "-Xclang", "-ast-dump=json", header], {
    encoding: "utf8", maxBuffer: 1 << 26, stdio: ["ignore", "pipe", "pipe"],
  }));
  const names = new Set();
  const diagnostics = new Set();
  const entries = new Map();
  function visit(node) {
    if (node.kind === "FunctionDecl" && node.name?.startsWith(PREFIX)) { names.add(node.name.slice(PREFIX.length)); entries.set(node.name, node); }
    if (node.kind === "FunctionDecl" && node.name?.startsWith(DIAGNOSTIC_PREFIX)) { diagnostics.add(node.name.slice(DIAGNOSTIC_PREFIX.length)); entries.set(node.name, node); }
    for (const child of node.inner ?? []) visit(child);
  }
  visit(ast);
  if (names.size === 0) throw new Error(`${header}: no native callback entry points`);
  return {
    base: renderCallbacks(header, names, false), diagnostics: diagnostics.size ? renderCallbacks(header, diagnostics, true) : undefined,
    puregoBase: renderPuregoCallbacks(header, names, entries, false),
    puregoDiagnostics: diagnostics.size ? renderPuregoCallbacks(header, diagnostics, entries, true) : undefined,
  };
}

function renderCallbacks(header, names, diagnostics) {
  const macro = diagnostics ? "SP_HOST_DIAGNOSTIC_CALLBACKS" : "SP_HOST_CALLBACKS";
  const table = diagnostics ? "sp_host_diagnostic_callbacks" : "sp_host_callbacks";
  return `// Code generated by scripts/check-host-callbacks.mjs --write; DO NOT EDIT.
//go:build darwin${diagnostics ? " && diagnostics" : ""}

package darwin

/*
#include "${basename(header)}"
#define DECLARE_GO(mode, result, name, parameters, arguments) extern result goHost_##name parameters;
${macro}(DECLARE_GO)
#undef DECLARE_GO
*/
import "C"

func init() {
\tvar callbacks C.${table}
${[...names].map((name) => `\tcallbacks.${name} = (*[0]byte)(C.goHost_${name})`).join("\n")}
\tif failure := C.${table}_install(&callbacks); failure != nil {
\t\tpanic("native callback registration: " + C.GoString(failure))
\t}
}
`;
}

// This ABI is Darwin LP64. Opaque native structs remain pointers owned by native code.
function goType(header, type) {
  const value = type.replace(/\bconst\b/g, "").trim();
  const primitives = { void: "", _Bool: "bool", bool: "bool", char: "byte", int: "int32", long: "int64", "unsigned long": "uint64", "unsigned long long": "uint64", uint64_t: "uint64", uintptr_t: "uintptr", size_t: "uint64", double: "float64" };
  if (Object.hasOwn(primitives, value)) return primitives[value];
  if (/\*\s*$/.test(value)) {
    const pointed = value.replace(/\*\s*$/, "").trim();
    if (pointed === "void" || pointed === "sp_input_held") return "unsafe.Pointer";
    const element = goType(header, pointed);
    if (element) return "*" + element;
  }
  throw new Error(`${header}: unsupported callback type ${type}`);
}

function renderPuregoCallbacks(header, names, entries, diagnostics) {
  const profile = diagnostics ? "DiagnosticCallbacks" : "Callbacks";
  const table = diagnostics ? "DiagnosticTable" : "Table";
  const prefix = diagnostics ? DIAGNOSTIC_PREFIX : PREFIX;
  const callbacks = [...names].map((name) => {
    const node = entries.get(prefix + name);
    if (node.variadic) throw new Error(`${header}: unsupported variadic callback ${name}`);
    const result = goType(header, node.type.qualType.split(" (")[0]);
    if (result === "float64") throw new Error(`${header}: unsupported callback result double for ${name}`);
    const parameters = (node.inner ?? []).filter((entry) => entry.kind === "ParmVarDecl").map((entry) => goType(header, entry.type.qualType));
    return { name, field: name.split("_").map((part) => part[0].toUpperCase() + part.slice(1)).join(""), signature: `func(${parameters.join(", ")})${result ? " " + result : ""}` };
  });
  const source = `// Code generated by scripts/check-host-callbacks.mjs --write; DO NOT EDIT.
//go:build darwin${diagnostics ? " && diagnostics" : ""}

package nativecallback

import (
	"fmt"
${callbacks.some((entry) => entry.signature.includes("unsafe.Pointer")) ? '\t"unsafe"\n' : ""}
	"github.com/ebitengine/purego"
)

// ${profile} preserves the C signatures of ${basename(header)}.
type ${profile} struct {
${callbacks.map((entry) => `	${entry.field} ${entry.signature}`).join("\n")}
}

// ${table} holds function addresses in the native header's field order.
type ${table} [${callbacks.length}]uintptr

// Bind creates process-lifetime addresses. Call once at startup and reuse the table.
// All functions are validated before allocating any address. Native code copies the table.
func (callbacks ${profile}) Bind() (${table}, error) {
${callbacks.map((entry) => `	if callbacks.${entry.field} == nil {
		return ${table}{}, fmt.Errorf("native callback is missing: ${entry.name}")
	}`).join("\n")}
	return ${table}{
${callbacks.map((entry) => `		purego.NewCallback(callbacks.${entry.field}),`).join("\n")}
	}, nil
}
`;
  return execFileSync("gofmt", { input: source, encoding: "utf8" });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { values } = parseArgs({ options: { header: { type: "string" }, output: { type: "string" }, "purego-output": { type: "string" }, write: { type: "boolean" } } });
    const header = resolve(values.header ?? `${ROOT}native/darwin/src/host_callbacks.h`);
    const output = resolve(values.output ?? `${ROOT}packages/host/go/src/platform/darwin/callback_bindings.go`);
    const puregoOutput = values["purego-output"] ?? (values.output ? undefined : `${ROOT}packages/host/mygo/src/platform/darwin/nativecallback/callback_bindings.go`);
    const generated = createHostCallbacks(header);
    const files = [];
    for (const [baseFile, base, diagnostics] of [[output, generated.base, generated.diagnostics], ...(puregoOutput ? [[resolve(puregoOutput), generated.puregoBase, generated.puregoDiagnostics]] : [])]) {
      if (!baseFile.endsWith(".go")) throw new Error(`${baseFile}: callback binding output must end in .go`);
      files.push([baseFile, base]);
      const diagnosticFile = baseFile.slice(0, -3) + "_diagnostics.go";
      if (diagnostics) files.push([diagnosticFile, diagnostics]);
      else if (existsSync(diagnosticFile)) {
        const existing = readFileSync(diagnosticFile, "utf8");
        if (!existing.startsWith("// Code generated by scripts/check-host-callbacks.mjs --write; DO NOT EDIT.")) {
          throw new Error(`${diagnosticFile}: refusing to remove a file not owned by the callback generator`);
        }
        if (!values.write) throw new Error(`${diagnosticFile}: obsolete diagnostic callback binding; run make create-host-callbacks`);
        unlinkSync(diagnosticFile);
      }
    }
    for (const [file, text] of files) {
      const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
      if (current !== text) {
        if (!values.write) throw new Error(`${file}: callback binding is stale; run make create-host-callbacks`);
        writeFileSync(file, text);
      }
    }
    process.stdout.write(`Host callback binding ${values.write ? "written" : "checked"}: ${output}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}${error.stderr ? `\n${error.stderr}` : ""}\n`);
    process.exitCode = 1;
  }
}
