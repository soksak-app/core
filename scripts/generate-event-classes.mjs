// Generates the class tables that the writers and the gates of the producers use from the catalog of this repository
// (docs/spec/logging.md#classes-and-policy):
//   node scripts/generate-event-classes.mjs           writes the three tables;
//   node scripts/generate-event-classes.mjs --check   fails when a table differs from what the catalog gives.
// The catalog `docs/spec/events.json` owns the class of each event. A name with a placeholder declares a family whose
// placeholder is the end of the name, so a family is a prefix and one or more characters of `a-z`, `0-9`, `_` and `.`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const CATALOG = 'docs/spec/events.json';
const GO = 'packages/sok/wailsv3/src/event_classes.go';
const RUST = 'packages/sok/tauriv2/src/event_classes.rs';
const JS = 'packages/workbench/event-classes.js';
const HEADER = 'generated by scripts/generate-event-classes.mjs from docs/spec/events.json; change the catalog and run the script';

/** The classes of the catalog in the order of the contract, the exact names and the families `[prefix, class]`. */
export function classTables(catalog) {
  const order = ['lifecycle', 'input', 'call', 'io', 'frame'];
  const exact = [];
  const families = [];
  for (const [name, declared] of Object.entries(catalog.events)) {
    if (!order.includes(declared.class)) throw new Error(`${CATALOG}: ${name} has the class ${JSON.stringify(declared.class)}, which is not one of ${order.join(', ')}`);
    if (!name.includes('<')) {
      exact.push([name, declared.class]);
      continue;
    }
    const match = /^([a-z0-9_.]+\.)<[a-z_]+>$/.exec(name);
    if (match === null) throw new Error(`${CATALOG}: the family ${name} must end with its placeholder`);
    families.push([match[1], declared.class]);
  }
  exact.sort((a, b) => a[0].localeCompare(b[0]));
  families.sort((a, b) => a[0].localeCompare(b[0]));
  return { order, exact, families };
}

const pascal = (text) => text[0].toUpperCase() + text.slice(1);
// The width that gofmt aligns a block of lines to: the longest name and one space.
const widest = (names) => Math.max(...names.map((name) => name.length));

function goTable({ order, exact, families }) {
  const lines = [
    `// Code ${HEADER}.`,
    'package sok',
    '',
    '// Class is the class of an event (docs/spec/logging.md#classes-and-policy).',
    'type Class string',
    '',
    '// The classes of the catalog, in the order of the contract.',
    'const (',
    ...order.map((name) => `\t${`Class${pascal(name)}`.padEnd(widest(order.map((n) => `Class${pascal(n)}`)))} Class = ${JSON.stringify(name)}`),
    ')',
    '',
    '// Classes lists the classes in the order of the contract.',
    `var Classes = []Class{${order.map((name) => `Class${pascal(name)}`).join(', ')}}`,
    '',
    'var eventClasses = map[string]Class{',
    ...exact.map(([name, klass]) => `\t${`${JSON.stringify(name)}:`.padEnd(widest(exact.map(([n]) => `${JSON.stringify(n)}:`)))} Class${pascal(klass)},`),
    '}',
    '',
    'var eventClassFamilies = []struct {',
    '\tprefix string',
    '\tclass  Class',
    '}{',
    ...families.map(([prefix, klass]) => `\t{${JSON.stringify(prefix)}, Class${pascal(klass)}},`),
    '}',
    '',
    '// EventClassOf returns the class that the catalog gives the event name, and false for a name the catalog does not declare.',
    'func EventClassOf(name string) (Class, bool) {',
    '\tif class, found := eventClasses[name]; found {',
    '\t\treturn class, true',
    '\t}',
    '\tfor _, family := range eventClassFamilies {',
    '\t\tif len(name) > len(family.prefix) && name[:len(family.prefix)] == family.prefix && familyTail(name[len(family.prefix):]) {',
    '\t\t\treturn family.class, true',
    '\t\t}',
    '\t}',
    '\treturn "", false',
    '}',
    '',
    '// familyTail reports whether text is one or more characters of `a-z`, `0-9`, `_` and `.`, which a placeholder stands for.',
    'func familyTail(text string) bool {',
    '\tfor index := 0; index < len(text); index++ {',
    '\t\tc := text[index]',
    "\t\tif !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '_' || c == '.') {",
    '\t\t\treturn false',
    '\t\t}',
    '\t}',
    '\treturn true',
    '}',
    '',
  ];
  return lines.join('\n');
}

function rustTable({ order, exact, families }) {
  const lines = [
    `//! The class of each event of the catalog; ${HEADER}.`,
    '',
    '/// The class of an event (docs/spec/logging.md#classes-and-policy).',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]',
    'pub enum Class {',
    ...order.map((name) => `    ${pascal(name)},`),
    '}',
    '',
    'impl Class {',
    '    /// The classes in the order of the contract.',
    `    pub const ALL: [Class; ${order.length}] = [`,
    ...order.map((name) => `        Class::${pascal(name)},`),
    '    ];',
    '',
    '    /// The name of the class in the line of an event and in the policy.',
    '    pub fn as_str(self) -> &\'static str {',
    '        match self {',
    ...order.map((name) => `            Class::${pascal(name)} => ${JSON.stringify(name)},`),
    '        }',
    '    }',
    '',
    '    /// The class with the name, or `None` for a name that is not a class.',
    '    pub fn parse(name: &str) -> Option<Class> {',
    '        match name {',
    ...order.map((name) => `            ${JSON.stringify(name)} => Some(Class::${pascal(name)}),`),
    '            _ => None,',
    '        }',
    '    }',
    '}',
    '',
    'const FAMILIES: &[(&str, Class)] = &[',
    ...families.map(([prefix, klass]) => `    (${JSON.stringify(prefix)}, Class::${pascal(klass)}),`),
    '];',
    '',
    '/// The class that the catalog gives the event name, and `None` for a name the catalog does not declare.',
    'pub fn class_of(name: &str) -> Option<Class> {',
    '    let exact = match name {',
    ...exact.map(([name, klass]) => `        ${JSON.stringify(name)} => Some(Class::${pascal(klass)}),`),
    '        _ => None,',
    '    };',
    '    if exact.is_some() {',
    '        return exact;',
    '    }',
    '    for (prefix, class) in FAMILIES {',
    '        if let Some(tail) = name.strip_prefix(prefix)',
    '            && !tail.is_empty()',
    '            && tail.bytes().all(is_tail_byte)',
    '        {',
    '            return Some(*class);',
    '        }',
    '    }',
    '    None',
    '}',
    '',
    '/// A byte that a placeholder of a family stands for: `a-z`, `0-9`, `_` or `.`.',
    'fn is_tail_byte(byte: u8) -> bool {',
    "    byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_' || byte == b'.'",
    '}',
    '',
  ];
  return lines.join('\n');
}

function jsTable({ order, exact, families }) {
  const lines = [
    `// The class of each event of the catalog; ${HEADER}.`,
    '',
    '/** The classes in the order of the contract (docs/spec/logging.md#classes-and-policy). */',
    `export const CLASSES = ${JSON.stringify(order)};`,
    '',
    'const EXACT = new Map([',
    ...exact.map(([name, klass]) => `  [${JSON.stringify(name)}, ${JSON.stringify(klass)}],`),
    ']);',
    '',
    'const FAMILIES = [',
    ...families.map(([prefix, klass]) => `  [${JSON.stringify(prefix)}, ${JSON.stringify(klass)}],`),
    '];',
    '',
    'const TAIL = /^[a-z0-9_.]+$/;',
    '',
    '/** The class that the catalog gives the event name, and `undefined` for a name the catalog does not declare. */',
    'export function classOf(name) {',
    '  const exact = EXACT.get(name);',
    '  if (exact !== undefined) return exact;',
    '  for (const [prefix, klass] of FAMILIES) {',
    '    if (name.startsWith(prefix) && TAIL.test(name.slice(prefix.length))) return klass;',
    '  }',
    '  return undefined;',
    '}',
    '',
  ];
  return lines.join('\n');
}

/** The three tables by path. */
export function generatedTables() {
  const tables = classTables(JSON.parse(readFileSync(new URL(`../${CATALOG}`, import.meta.url), 'utf8')));
  return { [GO]: goTable(tables), [RUST]: rustTable(tables), [JS]: jsTable(tables) };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const tables = generatedTables();
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [path, text] of Object.entries(tables)) {
    let current = null;
    try {
      current = readFileSync(`${ROOT}${path}`, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (current === text) continue;
    if (check) stale.push(path);
    else writeFileSync(`${ROOT}${path}`, text);
  }
  if (stale.length > 0) {
    console.error(`${stale.join(', ')}: differ from ${CATALOG}; run node scripts/generate-event-classes.mjs`);
    process.exit(1);
  }
}
