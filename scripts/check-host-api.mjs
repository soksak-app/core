// Native headers own the outbound ABI. Clang resolves declarations and constant expressions.
import {execFileSync} from 'node:child_process';
import {existsSync, readFileSync, writeFileSync, mkdirSync, unlinkSync} from 'node:fs';
import {resolve, dirname, basename} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {parseArgs} from 'node:util';

const ROOT=fileURLToPath(new URL('../',import.meta.url));
const ABI='github.com/soksak-app/core/packages/host/go/src/platform/darwin/abi';
const MARKER='// Code generated by scripts/check-host-api.mjs --write; DO NOT EDIT.';
const camel=name=>name.split('_').map(part=>part[0].toUpperCase()+part.slice(1)).join('');
function clang(header,source){
 const args=['-x',source===undefined?'c-header':'c','-fblocks','-DSOKSAK_DIAGNOSTIC','-fsyntax-only','-Xclang','-ast-dump=json'];
 if(source!==undefined)args.push('-include',header,'-');else args.push(header);
 return JSON.parse(execFileSync('clang',args,{input:source,encoding:'utf8',maxBuffer:1<<27,stdio:['pipe','pipe','pipe']}));
}
function nodes(ast){const all=[];function visit(node){all.push(node);for(const child of node.inner??[])visit(child);}visit(ast);return all;}
function format(source){return execFileSync('gofmt',{input:source,encoding:'utf8'});}

export function createHostApi(header,manifest,{abiImport=ABI,pkgConfig="soksak-darwin"}={}){
 const all=nodes(clang(header));
 const declarations=new Map(all.filter(n=>n.kind==='FunctionDecl').map(n=>[n.name,n]));
 const typedefs=new Map(all.filter(n=>n.kind==='TypedefDecl').map(n=>[n.name,n]));
 const recordsById=new Map(all.filter(n=>n.kind==='RecordDecl'&&n.completeDefinition).map(n=>[n.id,n]));
 const recordNames=new Set(manifest.records??[]);
 const primitives=new Map(Object.entries({void:'',_Bool:'bool',bool:'bool',char:'byte','signed char':'int8','unsigned char':'uint8',short:'int16','unsigned short':'uint16',int:'int32','unsigned int':'uint32',long:'int64','unsigned long':'uint64','long long':'int64','unsigned long long':'uint64',int8_t:'int8',uint8_t:'uint8',int16_t:'int16',uint16_t:'uint16',int32_t:'int32',uint32_t:'uint32',int64_t:'int64',uint64_t:'uint64',uintptr_t:'uintptr',intptr_t:'int64',size_t:'uint64',double:'float64',float:'float32'}));
 function type(raw,seen=new Set()){
  const c=raw.replace(/\bconst\b/g,'').replace(/\s+/g,' ').trim();
  if(primitives.has(c))return {go:primitives.get(c),c,kind:'scalar'};
  if(recordNames.has(c))return {go:camel(c),c,kind:'record'};
  if(/\*\s*$/.test(c)){
   const base=c.replace(/\*\s*$/,'').trim();
   if(base==='void')return {go:'unsafe.Pointer',c,kind:'voidPointer'};
   const target=type(base,seen);
   if(!target.go)throw new Error(`${header}: unsupported native API type ${raw}`);
   return {go:'*'+target.go,c,kind:'pointer'};
  }
  const alias=typedefs.get(c);
  if(alias&&!seen.has(c)){
   const target=alias.type?.desugaredQualType??alias.type?.qualType;
   if(target&&target!==c){const next=new Set(seen);next.add(c);return {...type(target,next),c};}
  }
  throw new Error(`${header}: unsupported native API type ${raw}`);
 }
 const records=[...recordNames].map(name=>{
  const alias=typedefs.get(name);
  const tag=nodes(alias??{}).find(n=>n.ownedTagDecl?.kind==='RecordDecl')?.ownedTagDecl;
  let record=tag?recordsById.get(tag.id):undefined;
  if(!record){const actual=alias?.type?.desugaredQualType??alias?.type?.qualType;record=all.find(n=>n.kind==='RecordDecl'&&n.completeDefinition&&(actual===`struct ${n.name}`));}
  if(!record||record.tagUsed==='union'||record.inner?.some(n=>n.kind==='PackedAttr'))throw new Error(`${header}: unsupported native API record ${name}`);
  const fields=(record.inner??[]).filter(n=>n.kind==='FieldDecl').map(field=>{
   if(!field.name||field.isBitfield)throw new Error(`${header}: unsupported native API record field in ${name}`);
   return {name:field.name,field:camel(field.name),type:type(field.type.qualType)};
  });
  if(fields.length===0)throw new Error(`${header}: unsupported empty native API record ${name}`);
  return {name,go:camel(name),fields};
 });
 const fieldNames=new Set();
 function functions(names){return names.map(name=>{
  const node=declarations.get(name);
  if(!node)throw new Error(`${header}: native API declaration is missing: ${name}`);
  if(node.variadic)throw new Error(`${header}: unsupported variadic native API function ${name}`);
  const match=node.type.qualType.match(/^(.*?)\s*\(/);
  if(!match)throw new Error(`${header}: unsupported native API signature ${node.type.qualType}`);
  const result=type(match[1]);
  const parameters=(node.inner??[]).filter(n=>n.kind==='ParmVarDecl').map(n=>type(n.type.qualType));
  const field=camel(name);
  if(fieldNames.has(field))throw new Error(`${header}: duplicate native API field ${field}`);
  fieldNames.add(field);
  return {name,field,result,parameters};
 });}
 const core=functions(manifest.core??[]),diagnostic=functions(manifest.diagnostics??[]);
 let constants=[];
 if(manifest.constants?.length||records.length){
  const expressions=[...(manifest.constants??[]).map((name,i)=>`enum { sp_host_api_constant_${i} = ${name} };`),...records.flatMap((record,i)=>[`enum { sp_host_api_size_${i} = sizeof(${record.name}) };`,...record.fields.map((field,j)=>`enum { sp_host_api_offset_${i}_${j} = __builtin_offsetof(${record.name}, ${field.name}) };`)])];
  const probes=nodes(clang(header,expressions.join('\n')));
  function evaluated(name){
   const decl=probes.find(n=>n.kind==='EnumConstantDecl'&&n.name===name);
   const value=nodes(decl??{}).find(n=>n.kind==='ConstantExpr'&&n.value!==undefined)?.value;
   if(!/^-?\d+$/.test(value??''))throw new Error(`${header}: unsupported native API constant expression ${name}`);
   return value;
  }
  constants=(manifest.constants??[]).map((name,i)=>({name,value:evaluated(`sp_host_api_constant_${i}`)}));
  for(const [i,record] of records.entries()){
   record.size=evaluated(`sp_host_api_size_${i}`);
   for(const [j,field] of record.fields.entries())field.offset=evaluated(`sp_host_api_offset_${i}_${j}`);
  }
 }
 const qualified=t=>t.go.replace(/\b([A-Z][A-Za-z0-9]*)\b/g,name=>name==='Pointer'?name:'abi.'+name);
 const signature=(fn,qualify=false,names=false)=>`func(${fn.parameters.map((p,i)=>(names?`a${i} `:'')+(qualify?qualified(p):p.go)).join(', ')})${fn.result.go?' '+(qualify?qualified(fn.result):fn.result.go):''}`;
 function shared(fns,diagnostics){
  const name=diagnostics?'DiagnosticFunctions':'NativeFunctions';
  const assertions=diagnostics?'':records.map(record=>`// Compile-time agreement with Clang's sizeof and field offsets.\nvar (\n_ [${record.size} - unsafe.Sizeof(${record.go}{})]byte\n_ [unsafe.Sizeof(${record.go}{}) - ${record.size}]byte\n${record.fields.map(field=>`_ [${field.offset} - unsafe.Offsetof(${record.go}{}.${field.field})]byte\n_ [unsafe.Offsetof(${record.go}{}.${field.field}) - ${field.offset}]byte`).join('\n')}\n)`).join('\n\n');
  const body=[...(!diagnostics?records.map(r=>`type ${r.go} struct {\n_ structs.HostLayout\n${r.fields.map(f=>`${f.field} ${f.type.go}`).join('\n')}\n}`):[]),...(!diagnostics?constants.map(c=>`const ${c.name} = ${c.value}`):[]),assertions,`type ${name} struct {\n${fns.map(fn=>`${fn.field} ${signature(fn)}`).join('\n')}\n}`,`func (functions ${name}) Validate() error {\n${fns.map(fn=>`if functions.${fn.field} == nil { return fmt.Errorf("native API function is missing: ${fn.name}") }`).join('\n')}\nreturn nil\n}`].join('\n\n');
  const imports=[...(!diagnostics&&records.length?['"structs"']:[]),...(fns.length?['"fmt"']:[]),...(body.includes('unsafe.')?['"unsafe"']:[])];
  return render('abi',imports,body,diagnostics);
 }
 function ctype(c){return c.startsWith('struct ')?'C.struct_'+c.slice(7):'C.'+({void:'void',_Bool:'bool',bool:'bool','signed char':'schar','unsigned char':'uchar',short:'short','unsigned short':'ushort','unsigned int':'uint',long:'long','unsigned long':'ulong','long long':'longlong','unsigned long long':'ulonglong'}[c]??c);}
 function toC(t,arg){
  if(t.kind==='voidPointer')return arg;
  if(t.kind==='pointer'){
   const stars=t.c.match(/\*\s*$/)?t.c.replace(/\s/g,'').match(/\*+$/)?.[0].length:0;
   const base=t.c.replace(/\*/g,'').trim();
   const target=base==='void'?'*'.repeat(stars-1)+'unsafe.Pointer':'*'.repeat(stars)+ctype(base);
   return `(${target})(unsafe.Pointer(${arg}))`;
  }
  if(t.kind==='record'){
   const record=records.find(r=>r.name===t.c);
   return `${ctype(t.c)}{${record.fields.map(f=>`${f.name}: ${toC(f.type,arg+'.'+f.field)}`).join(', ')}}`;
  }
  return `${ctype(t.c)}(${arg})`;
 }
 function fromC(t,arg){
  if(t.kind==='voidPointer')return arg;
  if(t.kind==='pointer')return `(${qualified(t)})(unsafe.Pointer(${arg}))`;
  if(t.kind==='record'){
   const record=records.find(r=>r.name===t.c);
   return `abi.${record.go}{${record.fields.map(f=>`${f.field}: ${fromC(f.type,arg+'.'+f.name)}`).join(', ')}}`;
  }
  return `${qualified(t)}(${arg})`;
 }
 function wails(fns,diagnostics){
  const name=diagnostics?'DiagnosticFunctions':'NativeFunctions',factory=diagnostics?'DiagnosticFunctions':'Functions';
  const body=`func ${factory}() abi.${name} {\nreturn abi.${name}{\n${fns.map(fn=>{
   const call=`C.${fn.name}(${fn.parameters.map((p,i)=>toC(p,'a'+i)).join(', ')})`;
   let expression=call;
   if(fn.result.go)expression=fn.result.kind==='record'?`result := ${call}\nreturn ${fromC(fn.result,'result')}`:`return ${fromC(fn.result,call)}`;
   return `${fn.field}: ${signature(fn,true,true)} { ${expression} },`;
  }).join('\n')}\n}\n}`;
  const imports=[`abi "${abiImport}"`,...(body.includes('unsafe.')?['"unsafe"']:[])];
  return render('bindings',imports,body,diagnostics,`/*\n#cgo pkg-config: ${pkgConfig}\n${diagnostics ? "#cgo CFLAGS: -DSOKSAK_DIAGNOSTIC\n" : ""}#include "${basename(header)}"\n*/\nimport "C"\n`);
 }
 function mygo(fns,diagnostics){
  const name=diagnostics?'DiagnosticFunctions':'NativeFunctions',factory=diagnostics?'DiagnosticFunctions':'Functions';
  const body=`func ${factory}(library uintptr) (abi.${name}, error) {\nvar functions abi.${name}\n${fns.map(fn=>`{\naddress, err := purego.Dlsym(library, "${fn.name}")\nif err != nil { return abi.${name}{}, fmt.Errorf("native API ${fn.name}: %w", err) }\nif address == 0 { return abi.${name}{}, fmt.Errorf("native API ${fn.name}: symbol has a null address") }\npurego.RegisterFunc(&functions.${fn.field}, address)\n}`).join('\n')}\nreturn functions, nil\n}`;
  return render('bindings',[`abi "${abiImport}"`,...(fns.length?['"fmt"','"github.com/ebitengine/purego"']:[])],body,diagnostics);
 }
 function render(pkg,imports,body,diagnostics,preamble=''){
  return format(`${MARKER}\n//go:build darwin${diagnostics?' && diagnostics':''}\n\npackage ${pkg}\n\n${preamble}${imports.length?`import (\n${imports.join('\n')}\n)\n`:''}\n${body}\n`);
 }
 return {shared:shared(core,false),sharedDiagnostics:shared(diagnostic,true),wails:wails(core,false),wailsDiagnostics:wails(diagnostic,true),mygo:mygo(core,false),mygoDiagnostics:mygo(diagnostic,true)};
}

